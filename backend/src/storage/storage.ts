/**
 * Object storage port + filesystem driver.
 *
 * The port is deliberately S3-shaped (flat keys, opaque bytes, atomic writes,
 * download through `createDownload`), so an S3 driver can be added later
 * without touching any caller. No S3 code is part of this build.
 */
import { createHash, randomUUID } from 'node:crypto';
import { createReadStream, createWriteStream } from 'node:fs';
import { mkdir, rename, rm, stat } from 'node:fs/promises';
import { dirname, isAbsolute, join, normalize, resolve } from 'node:path';
import { pipeline } from 'node:stream/promises';
import type { Readable } from 'node:stream';

export interface PutResult {
  key: string;
  size: number;
  checksumSha256: string;
}

export type DownloadPlan = { kind: 'stream'; stream: Readable } | { kind: 'redirect'; url: string };

export interface StorageProvider {
  readonly backend: 'fs';
  put(key: string, stream: Readable, meta?: { contentType?: string }): Promise<PutResult>;
  getStream(key: string): Promise<Readable>;
  createDownload(key: string, opts: { fileName: string; contentType: string; ttlSeconds: number }): Promise<DownloadPlan>;
  delete(key: string): Promise<void>;
  head(key: string): Promise<{ exists: boolean; size: number }>;
}

/** Key scheme (shared by every driver) — see docs/backend/40-data-model.md §4.8. */
export const storageKeys = {
  shard: (applicationId: number) => String(Math.floor(applicationId / 1000)).padStart(6, '0'),
  applicationDocument: (applicationId: number, ext: string) =>
    `applications/${storageKeys.shard(applicationId)}/${applicationId}/documents/${randomUUID()}${ext}`,
  requestedDocument: (applicationId: number, ext: string) =>
    `applications/${storageKeys.shard(applicationId)}/${applicationId}/requested/${randomUUID()}${ext}`,
  deptDocument: (applicationId: number, ext: string) =>
    `applications/${storageKeys.shard(applicationId)}/${applicationId}/dept/${randomUUID()}${ext}`,
  decisionDocument: (applicationId: number) =>
    `applications/${storageKeys.shard(applicationId)}/${applicationId}/decision/${randomUUID()}.pdf`,
  blockPlan: (applicationId: number, blockNo: number, ext: string) =>
    `applications/${storageKeys.shard(applicationId)}/${applicationId}/blocks/${blockNo}/plans/${randomUUID()}${ext}`,
};

export class FilesystemStorage implements StorageProvider {
  readonly backend = 'fs' as const;

  constructor(private readonly root: string) {
    if (!isAbsolute(root)) throw new Error('FS_STORAGE_ROOT must be an absolute path.');
  }

  private resolveKey(key: string): string {
    // Keys are generated by `storageKeys` and never contain user input; anything
    // else is rejected rather than sanitised.
    if (!key || key.startsWith('/') || key.includes('..') || key !== normalize(key)) {
      throw new Error(`Invalid storage key "${key}".`);
    }
    const full = resolve(join(this.root, key));
    if (!full.startsWith(resolve(this.root) + '/')) throw new Error(`Invalid storage key "${key}".`);
    return full;
  }

  async put(key: string, stream: Readable): Promise<PutResult> {
    const target = this.resolveKey(key);
    await mkdir(dirname(target), { recursive: true, mode: 0o750 });
    const temp = `${target}.${randomUUID()}.part`;
    const hash = createHash('sha256');
    let size = 0;
    stream.on('data', (chunk: Buffer) => {
      hash.update(chunk);
      size += chunk.length;
    });
    await pipeline(stream, createWriteStream(temp, { mode: 0o640 }));
    await rename(temp, target); // atomic from the reader's point of view
    return { key, size, checksumSha256: hash.digest('hex') };
  }

  async getStream(key: string): Promise<Readable> {
    return createReadStream(this.resolveKey(key));
  }

  async createDownload(key: string): Promise<DownloadPlan> {
    // The filesystem driver always streams. An S3 driver would return
    // { kind: 'redirect', url: <presigned URL> } here; callers handle both.
    return { kind: 'stream', stream: await this.getStream(key) };
  }

  async delete(key: string): Promise<void> {
    await rm(this.resolveKey(key), { force: true });
  }

  async head(key: string): Promise<{ exists: boolean; size: number }> {
    try {
      const st = await stat(this.resolveKey(key));
      return { exists: true, size: st.size };
    } catch {
      return { exists: false, size: 0 };
    }
  }
}

export function createStorage(driver: 'fs', root: string): StorageProvider {
  if (driver !== 'fs') throw new Error(`Storage driver "${driver}" is not built in this phase.`);
  return new FilesystemStorage(root);
}
